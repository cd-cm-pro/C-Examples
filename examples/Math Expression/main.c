#include <stdio.h>

int main(void) {
    printf("1 + 1 = %d\n", 1 + 1);
    printf("5 - 2 = %d\n", 5 - 2);
    printf("3920 + 1034 = %d\n", 3920 + 1034);
    printf("123 * 593 = %d\n", 123 * 593);
    printf("100 / 5 = %d\n", 100 / 5);
    printf("0.1 + 0.2 = %f\n", 0.1f + 0.2f);
    printf("1233 / 2 = %f", 1233.0f / 2.0f);
    return 0;
}